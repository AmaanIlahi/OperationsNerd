"""A control registry and a private PostgreSQL database for each business.

Database names are server generated. No browser-supplied connection strings or
database names are accepted. Failed provisioning is retained for inspection;
creating a business never drops or resets another database.
"""
from __future__ import annotations

from contextlib import contextmanager
import json
import os
import re
from uuid import uuid4

from fastapi import HTTPException, Request
from starlette.responses import JSONResponse

from db import db as d
from db.runtime import database_scope


def enabled():
    return os.getenv("OPERATIONS_UMBRELLA_ENABLED", "0") == "1"


def configured():
    return enabled() and os.getenv("OPERATIONS_DATABASE_URL", "").startswith(("postgres://", "postgresql://"))


def initialize_registry():
    if not enabled():
        return
    if not configured():
        raise RuntimeError("The umbrella runtime requires OPERATIONS_DATABASE_URL pointing to PostgreSQL")
    with d.control_conn() as conn:
        conn.execute("""CREATE TABLE IF NOT EXISTS business_registry (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            owner_key TEXT NOT NULL, name TEXT NOT NULL, template TEXT,
            database_name TEXT NOT NULL UNIQUE,
            status TEXT NOT NULL CHECK(status IN ('provisioning','ready','failed')),
            created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC',now()),'YYYY-MM-DD HH24:MI:SS'))""")
        ready = conn.execute("SELECT id,database_name FROM business_registry WHERE status='ready'").fetchall()
    # An installation's host metadata upgrades independently; one failed
    # business never prevents the other private databases from starting.
    from umbrella.lifecycle import ensure_schema
    for business in ready:
        try:
            url = connection_url(business["database_name"])
            d.init_db(url)
            with database_scope(url), d.get_conn() as conn:
                ensure_schema(conn)
        except Exception:
            with d.control_conn() as conn:
                conn.execute("UPDATE business_registry SET status='failed' WHERE id=?", (business["id"],))


def connection_url(database_name):
    from urllib.parse import parse_qsl, urlencode, urlsplit, urlunsplit
    parsed = urlsplit(os.environ["OPERATIONS_DATABASE_URL"])
    query = urlencode([(key, value) for key, value in parse_qsl(parsed.query) if key.lower() not in ("dbname", "database")])
    return urlunsplit((parsed.scheme, parsed.netloc, "/" + database_name, query, ""))


def _registry(account_id, business_id, *, ready=True):
    with d.control_conn() as conn:
        row = conn.execute("SELECT * FROM business_registry WHERE id=? AND owner_key=?",
                           (business_id, str(account_id))).fetchone()
    if row is None:
        raise HTTPException(404, "Business not found")
    if ready and row["status"] != "ready":
        raise HTTPException(409, "This business is not ready; its database setup needs attention")
    return row


@contextmanager
def scope(account_id, business_id, *, ready=True):
    row = _registry(account_id, business_id, ready=ready)
    with database_scope(connection_url(row["database_name"])):
        yield row


def _initialize_registered_business(account_id, registration, spec=None):
    import psycopg
    from psycopg import sql
    from agentic import store, template_store
    from agentic.spec import empty_spec, rekey_spec
    from umbrella.base import with_common_base
    from umbrella.lifecycle import ensure_schema
    business_id, database_name = registration["id"], registration["database_name"]
    if not re.fullmatch(r"opsnerd_biz_[0-9a-f]{32}", database_name):
        raise RuntimeError("Invalid private database identity in the registry")
    admin_url = os.getenv("OPERATIONS_ADMIN_DATABASE_URL") or os.environ["OPERATIONS_DATABASE_URL"]
    with psycopg.connect(admin_url, autocommit=True, connect_timeout=10) as admin:
        if not admin.execute("SELECT 1 FROM pg_database WHERE datname=%s", (database_name,)).fetchone():
            admin.execute(sql.SQL("CREATE DATABASE {} TEMPLATE template0").format(sql.Identifier(database_name)))
    url = connection_url(database_name)
    d.init_db(url)
    with database_scope(url), d.get_conn() as conn:
        conn.execute("BEGIN IMMEDIATE")
        rows = conn.execute("SELECT id,owner_key FROM businesses").fetchall()
        if any(row["id"] != business_id or row["owner_key"] != str(account_id) for row in rows):
            raise RuntimeError("The database belongs to another business")
        existing = store.get_business_with_spec(conn, account_id, business_id) if rows else None
        if existing is None:
            if spec is None:
                template = template_store.get_template(registration["template"]) if registration["template"] else None
                if registration["template"] and template is None:
                    raise RuntimeError("The selected initial template is unavailable")
                spec = rekey_spec(template) if template else empty_spec(registration["name"])
                spec["business"]["name"] = registration["name"]
            spec = with_common_base(spec)
            conn.execute("""INSERT INTO businesses(id,name,industry_pack,pack_version,settings_json,owner_key,current_version)
                VALUES(?,?,?,?,?,?,1)""", (business_id, registration["name"], registration["template"] or store.AGENTIC_PACK,
                store.AGENTIC_PACK_VERSION, "{}", str(account_id)))
            conn.execute("""INSERT INTO spec_versions(business_id,version,spec_json,ops_json,source,approved_by)
                VALUES(?,1,?,'[]','template',?)""", (business_id, json.dumps(spec), account_id))
        ensure_schema(conn)
        return store.get_business_with_spec(conn, account_id, business_id)


def retry_provision(account_id, business_id, *, initial_spec=None):
    registration = _registry(account_id, business_id, ready=False)
    control_url = os.environ["OPERATIONS_DATABASE_URL"]
    with d.raw_postgres_conn(control_url) as lock:
        acquired = lock.execute("SELECT pg_try_advisory_lock(hashtextextended(%s,0))",
                               ("business-provision:" + str(business_id),)).fetchone()[0]
        if not acquired:
            raise HTTPException(409, "This business is already being set up; retry shortly")
        try:
            with d.control_conn() as conn:
                conn.execute("UPDATE business_registry SET status='provisioning' WHERE id=?", (business_id,))
            try:
                result = _initialize_registered_business(account_id, registration, initial_spec)
                with d.control_conn() as conn:
                    conn.execute("UPDATE business_registry SET status='ready' WHERE id=?", (business_id,))
                return result
            except Exception:
                with d.control_conn() as conn:
                    conn.execute("UPDATE business_registry SET status='failed' WHERE id=?", (business_id,))
                raise HTTPException(503, "Business setup could not complete. Its database is retained; retry after fixing connectivity or permissions.") from None
        finally:
            lock.execute("SELECT pg_advisory_unlock(hashtextextended(%s,0))",
                         ("business-provision:" + str(business_id),))


def provision(account_id, name, template, spec):
    database_name = "opsnerd_biz_" + uuid4().hex
    with d.control_conn() as conn:
        row = conn.execute("""INSERT INTO business_registry(owner_key,name,template,database_name,status)
            VALUES(?,?,?,?,'provisioning') RETURNING id""",
            (str(account_id), name, template, database_name)).fetchone()
    return retry_provision(account_id, row["id"], initial_spec=spec)


def list_owned(account_id):
    from agentic import store
    with d.control_conn() as conn:
        rows = conn.execute("SELECT * FROM business_registry WHERE owner_key=? ORDER BY id",
                            (str(account_id),)).fetchall()
    result = []
    for row in rows:
        if row["status"] != "ready":
            result.append({"id": row["id"], "name": row["name"], "template": row["template"],
                           "current_version": None, "status": row["status"], "created_at": row["created_at"]})
            continue
        with database_scope(connection_url(row["database_name"])):
            try:
                with d.get_conn() as conn:
                    business = store.get_business_with_spec(conn, account_id, row["id"])
                    result.append({key: value for key, value in business.items() if key != "spec"})
            except Exception:
                result.append({"id": row["id"], "name": row["name"], "template": row["template"],
                               "current_version": None, "status": "unavailable", "created_at": row["created_at"]})
    return result


class BusinessRoutingMiddleware:
    """Authenticate before selecting a business database, including proposals.

    Legacy proposal URLs have database-local IDs. They require X-Business-Id
    in umbrella mode so two businesses' proposal #1 can never be confused.
    """
    def __init__(self, app):
        self.app = app

    async def __call__(self, scope_data, receive, send):
        if scope_data["type"] != "http" or not enabled():
            return await self.app(scope_data, receive, send)
        path = scope_data.get("path", "")
        match = re.match(r"^/api/businesses/([1-9][0-9]{0,18})(?:/|$)", path)
        request = Request(scope_data)
        bid = int(match.group(1)) if match else None
        if path.startswith("/api/businesses/") and (bid is None or bid > 9223372036854775807):
            return await JSONResponse({"detail": "Use a valid business identifier"}, status_code=400)(scope_data, receive, send)
        if path.startswith("/api/proposals/"):
            supplied = request.headers.get("x-business-id", "")
            if not re.fullmatch(r"[1-9][0-9]{0,18}", supplied) or int(supplied) > 9223372036854775807:
                return await JSONResponse({"detail": "Select the business for this proposal"}, status_code=400)(scope_data, receive, send)
            bid = int(supplied)
        if bid is None:
            return await self.app(scope_data, receive, send)
        try:
            from agentic import auth
            account = auth.current_account(request)
            with globals()["scope"](account["id"], bid, ready=not path.endswith("/retry-setup")):
                await self.app(scope_data, receive, send)
        except HTTPException as error:
            await JSONResponse({"detail": error.detail}, status_code=error.status_code)(scope_data, receive, send)
