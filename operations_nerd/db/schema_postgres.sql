-- Initial PostgreSQL core migration. Keep immutable after application.
-- All operational data lives under core; domain modules own other schemas.
-- Accounts/session tables are used only in the control database.
-- An empty copy of their table definitions is harmless in a business database;
-- the host must never copy credentials or resolve sessions there.
SET LOCAL search_path TO core, public;


CREATE TABLE IF NOT EXISTS businesses (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            TEXT NOT NULL,
    industry_pack   TEXT NOT NULL,         -- e.g. 'realestate' -- which Config Pack is loaded
    pack_version    TEXT NOT NULL,
    settings_json   TEXT NOT NULL DEFAULT '{}',  -- questionnaire answers, shape defined by the pack
    created_at      TEXT NOT NULL DEFAULT (to_char(timezone('UTC', statement_timestamp()), 'YYYY-MM-DD HH24:MI:SS'))
);

ALTER TABLE businesses ADD COLUMN IF NOT EXISTS owner_key TEXT;
ALTER TABLE businesses ADD COLUMN IF NOT EXISTS current_version BIGINT;

CREATE TABLE IF NOT EXISTS contacts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id     BIGINT NOT NULL REFERENCES businesses(id),
    name            TEXT NOT NULL,
    email           TEXT,
    phone           TEXT,
    status          TEXT NOT NULL DEFAULT 'active',  -- active | inactive, universal enough to stay core
    created_at      TEXT NOT NULL DEFAULT (to_char(timezone('UTC', statement_timestamp()), 'YYYY-MM-DD HH24:MI:SS')),
    updated_at      TEXT NOT NULL DEFAULT (to_char(timezone('UTC', statement_timestamp()), 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS follow_ups (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id     BIGINT NOT NULL REFERENCES businesses(id),
    contact_id      BIGINT NOT NULL REFERENCES contacts(id),
    type            TEXT NOT NULL,          -- e.g. call, email, meeting -- values come from the pack's event schema
    status          TEXT NOT NULL DEFAULT 'pending',  -- pending | done | dismissed
    due_date        TEXT,
    notes           TEXT,
    created_at      TEXT NOT NULL DEFAULT (to_char(timezone('UTC', statement_timestamp()), 'YYYY-MM-DD HH24:MI:SS')),
    updated_at      TEXT NOT NULL DEFAULT (to_char(timezone('UTC', statement_timestamp()), 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS entity_attributes (
    entity_type     TEXT NOT NULL,      -- 'contact' | 'follow_up'
    entity_id       BIGINT NOT NULL,
    attribute_name  TEXT NOT NULL,
    value           TEXT NOT NULL,
    PRIMARY KEY (entity_type, entity_id, attribute_name)
);

CREATE INDEX IF NOT EXISTS idx_entity_attributes_lookup ON entity_attributes(entity_type, attribute_name, value);

CREATE TABLE IF NOT EXISTS events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id     BIGINT NOT NULL REFERENCES businesses(id),
    contact_id      BIGINT REFERENCES contacts(id),   -- nullable: may not be resolved yet
    source          TEXT NOT NULL,           -- email | call_note | form
    raw_content     TEXT NOT NULL,
    parsed_data     TEXT NOT NULL DEFAULT '{}',  -- structured output of the pipeline's LLM call
    processed       BIGINT NOT NULL DEFAULT 0,  -- 0/1 boolean
    received_at     TEXT NOT NULL DEFAULT (to_char(timezone('UTC', statement_timestamp()), 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS drafted_actions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id        BIGINT NOT NULL REFERENCES events(id),
    business_id     BIGINT NOT NULL REFERENCES businesses(id),
    contact_id      BIGINT REFERENCES contacts(id),
    action_type     TEXT NOT NULL,           -- e.g. send_follow_up_email -- pack-defined vocabulary
    payload         TEXT NOT NULL DEFAULT '{}',  -- drafted content (subject, body, etc.)
    status          TEXT NOT NULL DEFAULT 'pending_approval',
    created_at      TEXT NOT NULL DEFAULT (to_char(timezone('UTC', statement_timestamp()), 'YYYY-MM-DD HH24:MI:SS')),
    decided_at      TEXT
);

CREATE TABLE IF NOT EXISTS approval_policies (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id     BIGINT NOT NULL REFERENCES businesses(id),
    action_type     TEXT NOT NULL,
    auto_approve    BIGINT NOT NULL DEFAULT 0,  -- 0/1 boolean
    created_at      TEXT NOT NULL DEFAULT (to_char(timezone('UTC', statement_timestamp()), 'YYYY-MM-DD HH24:MI:SS')),
    updated_at      TEXT NOT NULL DEFAULT (to_char(timezone('UTC', statement_timestamp()), 'YYYY-MM-DD HH24:MI:SS')),
    UNIQUE(business_id, action_type)
);

CREATE INDEX IF NOT EXISTS idx_contacts_business ON contacts(business_id);
CREATE INDEX IF NOT EXISTS idx_follow_ups_business ON follow_ups(business_id);
CREATE INDEX IF NOT EXISTS idx_follow_ups_contact ON follow_ups(contact_id);
CREATE INDEX IF NOT EXISTS idx_events_business ON events(business_id);
CREATE INDEX IF NOT EXISTS idx_drafted_actions_business ON drafted_actions(business_id);

CREATE TABLE IF NOT EXISTS entities (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id  BIGINT NOT NULL REFERENCES businesses(id),
    entity_type  TEXT NOT NULL,       -- crm_account | crm_contact | crm_lead
    created_at   TEXT NOT NULL DEFAULT (to_char(timezone('UTC', statement_timestamp()), 'YYYY-MM-DD HH24:MI:SS')),
    updated_at   TEXT NOT NULL DEFAULT (to_char(timezone('UTC', statement_timestamp()), 'YYYY-MM-DD HH24:MI:SS'))
);
CREATE INDEX IF NOT EXISTS idx_entities_business_type
    ON entities(business_id, entity_type);


CREATE TABLE IF NOT EXISTS accounts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           TEXT NOT NULL UNIQUE,
    password_hash   TEXT NOT NULL,
    created_at      TEXT NOT NULL DEFAULT (to_char(timezone('UTC', statement_timestamp()), 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS sessions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      BIGINT NOT NULL REFERENCES accounts(id),
    token_hash      TEXT NOT NULL UNIQUE,   -- the raw token only ever lives in the cookie
    expires_at      TEXT NOT NULL,
    created_at      TEXT NOT NULL DEFAULT (to_char(timezone('UTC', statement_timestamp()), 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS spec_versions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id     BIGINT NOT NULL REFERENCES businesses(id),
    version         BIGINT NOT NULL,
    spec_json       TEXT NOT NULL,
    ops_json        TEXT NOT NULL DEFAULT '[]',
    source          TEXT NOT NULL,          -- agent | revert | template
    proposal_id     BIGINT,
    approved_by     BIGINT,
    created_at      TEXT NOT NULL DEFAULT (to_char(timezone('UTC', statement_timestamp()), 'YYYY-MM-DD HH24:MI:SS')),
    UNIQUE(business_id, version)
);

CREATE TABLE IF NOT EXISTS proposals (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id         BIGINT NOT NULL REFERENCES businesses(id),
    base_version        BIGINT NOT NULL,
    messages_json       TEXT NOT NULL DEFAULT '[]',
    reply               TEXT,
    ops_json            TEXT NOT NULL DEFAULT '[]',
    rejected_ops_json   TEXT NOT NULL DEFAULT '[]',
    impact_json         TEXT NOT NULL DEFAULT '{}',
    status              TEXT NOT NULL DEFAULT 'pending',
    model               TEXT,
    input_tokens        BIGINT,
    output_tokens       BIGINT,
    latency_ms          BIGINT,
    created_at          TEXT NOT NULL DEFAULT (to_char(timezone('UTC', statement_timestamp()), 'YYYY-MM-DD HH24:MI:SS')),
    decided_at          TEXT
);

CREATE TABLE IF NOT EXISTS chat_usage (
    account_id      BIGINT NOT NULL REFERENCES accounts(id),
    day             TEXT NOT NULL,
    turns           BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (account_id, day)
);

CREATE INDEX IF NOT EXISTS idx_sessions_account ON sessions(account_id);
CREATE INDEX IF NOT EXISTS idx_sessions_expires ON sessions(expires_at);
CREATE INDEX IF NOT EXISTS idx_drafted_actions_event ON drafted_actions(event_id);
CREATE INDEX IF NOT EXISTS idx_events_contact ON events(contact_id);
CREATE INDEX IF NOT EXISTS idx_spec_versions_business ON spec_versions(business_id, version);
CREATE INDEX IF NOT EXISTS idx_proposals_business ON proposals(business_id);

-- Actor IDs refer to the host's control database, never to copied accounts.
-- The approval audit intentionally has no local accounts foreign key.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conname = 'spec_versions_proposal_fk'
                     AND conrelid = 'core.spec_versions'::regclass) THEN
        ALTER TABLE core.spec_versions ADD CONSTRAINT spec_versions_proposal_fk
            FOREIGN KEY (proposal_id) REFERENCES core.proposals(id);
    END IF;
END $$;
