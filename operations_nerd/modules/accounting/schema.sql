CREATE FUNCTION accounting.guard_account() RETURNS trigger LANGUAGE plpgsql SET search_path=accounting,pg_temp AS $$
BEGIN
 PERFORM pg_advisory_xact_lock(1768842370,0);
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Accounts and funds are retained' USING ERRCODE='23514'; END IF;
 IF TG_OP='UPDATE' THEN
  IF TG_TABLE_NAME='accounts' THEN
   IF (NEW.id,NEW.code,NEW.account_type,NEW.role,NEW.is_capital) IS DISTINCT FROM (OLD.id,OLD.code,OLD.account_type,OLD.role,OLD.is_capital)
   THEN RAISE EXCEPTION 'Account identity, type, role and capital designation are permanent' USING ERRCODE='23514'; END IF;
  ELSE
   IF (NEW.id,NEW.code,NEW.restriction_type,NEW.is_default) IS DISTINCT FROM (OLD.id,OLD.code,OLD.restriction_type,OLD.is_default)
   THEN RAISE EXCEPTION 'Fund identity and restrictions are permanent' USING ERRCODE='23514'; END IF;
  END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER accounting_account_guard BEFORE INSERT OR UPDATE OR DELETE ON accounting.accounts FOR EACH ROW EXECUTE FUNCTION accounting.guard_account();
CREATE TRIGGER accounting_fund_guard BEFORE INSERT OR UPDATE OR DELETE ON accounting.funds FOR EACH ROW EXECUTE FUNCTION accounting.guard_account();

CREATE FUNCTION accounting.guard_entry() RETURNS trigger LANGUAGE plpgsql SET search_path=accounting,pg_temp AS $$
BEGIN
 PERFORM pg_advisory_xact_lock(1768842370,0);
 IF NEW.created_txid<>txid_current() THEN RAISE EXCEPTION 'Journal transaction identity is server assigned' USING ERRCODE='23514'; END IF;
 IF NEW.reverses_id IS NOT NULL AND NEW.entry_date<(SELECT entry_date FROM journal_entries WHERE id=NEW.reverses_id)
 THEN RAISE EXCEPTION 'A reversal cannot predate its original entry' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER accounting_entry_guard BEFORE INSERT ON accounting.journal_entries FOR EACH ROW EXECUTE FUNCTION accounting.guard_entry();
CREATE FUNCTION accounting.guard_line() RETURNS trigger LANGUAGE plpgsql SET search_path=accounting,pg_temp AS $$
BEGIN
 PERFORM pg_advisory_xact_lock(1768842370,0);
 IF NOT EXISTS(SELECT 1 FROM journal_entries WHERE id=NEW.entry_id AND created_txid=txid_current())
 THEN RAISE EXCEPTION 'Lines belong only to a journal entry created in this transaction' USING ERRCODE='23514'; END IF;
 IF NOT EXISTS(SELECT 1 FROM accounts WHERE id=NEW.account_id AND is_active)
 OR NOT EXISTS(SELECT 1 FROM funds WHERE id=NEW.fund_id AND is_active)
 THEN RAISE EXCEPTION 'Journal accounts and funds must be active' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER accounting_line_guard BEFORE INSERT ON accounting.journal_lines FOR EACH ROW EXECUTE FUNCTION accounting.guard_line();

CREATE FUNCTION accounting.check_journal() RETURNS trigger LANGUAGE plpgsql SET search_path=accounting,pg_temp AS $$
DECLARE eid bigint; e journal_entries%ROWTYPE; amount_debit numeric; amount_credit numeric; line_count bigint;
BEGIN
 IF TG_TABLE_NAME='journal_entries' THEN eid:=NEW.id; ELSE eid:=NEW.entry_id; END IF;
 SELECT * INTO e FROM journal_entries WHERE id=eid;
 SELECT count(*),COALESCE(sum(debit_minor),0),COALESCE(sum(credit_minor),0) INTO line_count,amount_debit,amount_credit FROM journal_lines WHERE entry_id=eid;
 IF line_count<2 OR amount_debit<>amount_credit OR amount_debit<>e.total_minor
 THEN RAISE EXCEPTION 'Journal entry must have at least two lines and equal debits, credits and total' USING ERRCODE='23514'; END IF;
 IF EXISTS(SELECT 1 FROM journal_lines WHERE entry_id=eid GROUP BY fund_id HAVING sum(debit_minor)<>sum(credit_minor))
 THEN RAISE EXCEPTION 'Each fund must balance within the journal entry' USING ERRCODE='23514'; END IF;
 IF e.reverses_id IS NOT NULL AND (
  (SELECT count(*) FROM journal_lines WHERE entry_id=e.reverses_id)<>line_count OR EXISTS(
   SELECT 1 FROM journal_lines o WHERE o.entry_id=e.reverses_id AND NOT EXISTS(
    SELECT 1 FROM journal_lines r WHERE r.entry_id=eid AND (r.line_no,r.account_id,r.fund_id,r.debit_minor,r.credit_minor)=
      (o.line_no,o.account_id,o.fund_id,o.credit_minor,o.debit_minor))))
 THEN RAISE EXCEPTION 'A reversal must mirror its original accounts, funds and amounts' USING ERRCODE='23514'; END IF;
 IF e.source='fund_release' AND EXISTS(SELECT 1 FROM journal_lines l JOIN funds f ON f.id=l.fund_id
                                     WHERE l.entry_id=eid AND f.restriction_type='permanently_restricted')
 THEN RAISE EXCEPTION 'Permanent funds remain restricted; releases are disabled' USING ERRCODE='23514'; END IF;
 -- A manual entry cannot disguise the same permanent-fund reclassification.
 -- Corrections use an exact reversal, which still passes the capacity timeline.
 IF e.source<>'reversal' AND EXISTS(SELECT 1 FROM journal_lines l JOIN funds f ON f.id=l.fund_id
  JOIN accounts a ON a.id=l.account_id WHERE l.entry_id=eid AND f.restriction_type='permanently_restricted'
  AND a.account_type IN('income','equity') GROUP BY l.fund_id HAVING sum(l.credit_minor-l.debit_minor)<0)
 THEN RAISE EXCEPTION 'Permanent fund income or equity cannot be released by a manual reclassification' USING ERRCODE='23514'; END IF;
 IF e.source IN('invoice','bill') AND NOT EXISTS(SELECT 1 FROM documents d
  WHERE d.posted_entry_id=eid AND d.kind=e.source AND d.id::text=e.source_ref)
 THEN RAISE EXCEPTION 'A document posting must belong to its matching document' USING ERRCODE='23514'; END IF;
 IF e.source IN('invoice_payment','bill_payment') AND NOT EXISTS(SELECT 1 FROM payments p JOIN documents d ON d.id=p.document_id
  WHERE p.entry_id=eid AND d.kind||'_payment'=e.source AND p.id::text=e.source_ref)
 THEN RAISE EXCEPTION 'A payment posting must belong to its matching payment' USING ERRCODE='23514'; END IF;
 IF e.reverses_id IS NOT NULL AND EXISTS(SELECT 1 FROM journal_entries o WHERE o.id=e.reverses_id AND o.source IN('invoice_payment','bill_payment'))
 THEN RAISE EXCEPTION 'Recorded payments require a refund workflow; direct reversals are unavailable' USING ERRCODE='23514'; END IF;
 IF e.reverses_id IS NOT NULL AND EXISTS(SELECT 1 FROM journal_entries o WHERE o.id=e.reverses_id AND o.source IN('invoice','bill'))
 AND NOT EXISTS(SELECT 1 FROM documents d WHERE d.posted_entry_id=e.reverses_id AND d.status='void' AND d.void_entry_id=eid)
 THEN RAISE EXCEPTION 'A document reversal requires its matching void transition' USING ERRCODE='23514'; END IF;
 -- Aggregate by date before taking a cumulative sum. This checks every later
 -- committed date too, so a backdated posting cannot invalidate the future.
 IF EXISTS(WITH daily AS (
  SELECT l.fund_id,j.entry_date,sum(CASE
    WHEN a.account_type IN('income','equity') THEN l.credit_minor-l.debit_minor
    WHEN a.account_type='expense' OR a.is_capital THEN l.credit_minor-l.debit_minor ELSE 0 END) AS delta
  FROM journal_lines l JOIN journal_entries j ON j.id=l.entry_id JOIN accounts a ON a.id=l.account_id
  JOIN funds f ON f.id=l.fund_id WHERE f.restriction_type<>'unrestricted' GROUP BY l.fund_id,j.entry_date),
  timeline AS(SELECT sum(delta) OVER(PARTITION BY fund_id ORDER BY entry_date ROWS UNBOUNDED PRECEDING) AS available FROM daily)
  SELECT 1 FROM timeline WHERE available<0)
 THEN RAISE EXCEPTION 'Restricted fund capacity would be negative on this or a later posted date' USING ERRCODE='23514'; END IF;
 RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER accounting_entry_balanced AFTER INSERT ON accounting.journal_entries DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION accounting.check_journal();
CREATE CONSTRAINT TRIGGER accounting_lines_balanced AFTER INSERT ON accounting.journal_lines DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION accounting.check_journal();

CREATE FUNCTION accounting.guard_document() RETURNS trigger LANGUAGE plpgsql SET search_path=accounting,pg_temp AS $$
BEGIN
 PERFORM pg_advisory_xact_lock(1768842370,0);
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Documents are retained; void them explicitly' USING ERRCODE='23514'; END IF;
 IF TG_OP='INSERT' THEN
  IF NEW.status<>'draft' OR NEW.posted_entry_id IS NOT NULL OR NEW.void_entry_id IS NOT NULL OR NEW.created_txid<>txid_current()
  THEN RAISE EXCEPTION 'Documents begin as drafts' USING ERRCODE='23514'; END IF;
 ELSE
  IF (NEW.id,NEW.kind,NEW.number,NEW.party_entity_key,NEW.party_record_id,NEW.issue_date,NEW.due_date,NEW.currency,NEW.fund_id,NEW.total_minor,NEW.actor_id,NEW.request_key,NEW.created_txid)
   IS DISTINCT FROM (OLD.id,OLD.kind,OLD.number,OLD.party_entity_key,OLD.party_record_id,OLD.issue_date,OLD.due_date,OLD.currency,OLD.fund_id,OLD.total_minor,OLD.actor_id,OLD.request_key,OLD.created_txid)
  THEN RAISE EXCEPTION 'Document terms are immutable' USING ERRCODE='23514'; END IF;
  IF NOT((OLD.status='draft' AND NEW.status IN('posted','void')) OR(OLD.status='posted' AND NEW.status='void'))
  THEN RAISE EXCEPTION 'Invalid document state transition' USING ERRCODE='23514'; END IF;
  IF OLD.status='posted' AND (NEW.party_snapshot<>OLD.party_snapshot OR NEW.posted_entry_id<>OLD.posted_entry_id)
  THEN RAISE EXCEPTION 'Posted party terms are frozen' USING ERRCODE='23514'; END IF;
  IF NEW.status='void' AND EXISTS(SELECT 1 FROM payments WHERE document_id=NEW.id)
  THEN RAISE EXCEPTION 'Paid documents require a refund or credit workflow; they cannot be voided' USING ERRCODE='23514'; END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER accounting_document_guard BEFORE INSERT OR UPDATE OR DELETE ON accounting.documents FOR EACH ROW EXECUTE FUNCTION accounting.guard_document();
CREATE FUNCTION accounting.guard_document_line() RETURNS trigger LANGUAGE plpgsql SET search_path=accounting,pg_temp AS $$
DECLARE d documents%ROWTYPE; a accounts%ROWTYPE;
BEGIN
 PERFORM pg_advisory_xact_lock(1768842370,0);
 SELECT * INTO d FROM documents WHERE id=NEW.document_id;
 SELECT * INTO a FROM accounts WHERE id=NEW.account_id;
 IF d.created_txid<>txid_current() OR d.status<>'draft' THEN RAISE EXCEPTION 'Draft lines are written with their document' USING ERRCODE='23514'; END IF;
 IF NOT a.is_active OR (d.kind='invoice' AND a.account_type<>'income') OR(d.kind='bill' AND a.account_type NOT IN('expense','asset'))
 OR a.role IN('accounts_receivable','accounts_payable')
 THEN RAISE EXCEPTION 'Invalid document line account type or control account' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER accounting_document_line_guard BEFORE INSERT ON accounting.document_lines FOR EACH ROW EXECUTE FUNCTION accounting.guard_document_line();
CREATE FUNCTION accounting.guard_payment() RETURNS trigger LANGUAGE plpgsql SET search_path=accounting,pg_temp AS $$
DECLARE d documents%ROWTYPE; paid numeric;
BEGIN
 PERFORM pg_advisory_xact_lock(1768842370,0);
 SELECT * INTO d FROM documents WHERE id=NEW.document_id FOR UPDATE;
 SELECT COALESCE(sum(amount_minor),0) INTO paid FROM payments WHERE document_id=NEW.document_id;
 IF d.status<>'posted' OR paid+NEW.amount_minor>d.total_minor OR NEW.payment_date<d.issue_date
 THEN RAISE EXCEPTION 'Payment requires a posted document, its remaining amount and a valid date' USING ERRCODE='23514'; END IF;
 IF NOT EXISTS(SELECT 1 FROM accounts WHERE id=NEW.cash_account_id AND is_active AND role='cash' AND NOT is_capital)
 THEN RAISE EXCEPTION 'Payment account must be an active cash or bank account' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER accounting_payment_guard BEFORE INSERT ON accounting.payments FOR EACH ROW EXECUTE FUNCTION accounting.guard_payment();
CREATE FUNCTION accounting.check_document() RETURNS trigger LANGUAGE plpgsql SET search_path=accounting,pg_temp AS $$
DECLARE d documents%ROWTYPE; did bigint;
BEGIN
 IF TG_TABLE_NAME='documents' THEN did:=NEW.id; ELSE did:=NEW.document_id; END IF;
 SELECT * INTO d FROM documents WHERE id=did;
 IF NOT EXISTS(SELECT 1 FROM document_lines WHERE document_id=did) OR
   (SELECT COALESCE(sum(amount_minor),0) FROM document_lines WHERE document_id=did)<>d.total_minor
 THEN RAISE EXCEPTION 'Document lines must match its exact total' USING ERRCODE='23514'; END IF;
 IF d.posted_entry_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM journal_entries WHERE id=d.posted_entry_id AND source=d.kind AND source_ref=d.id::text AND total_minor=d.total_minor AND entry_date=d.issue_date)
 THEN RAISE EXCEPTION 'Document must reference its own matching posting' USING ERRCODE='23514'; END IF;
 IF d.posted_entry_id IS NOT NULL AND EXISTS(
  WITH expected_lines AS (
   SELECT id AS account_id,d.fund_id AS fund_id,
    CASE WHEN d.kind='invoice' THEN d.total_minor ELSE 0 END AS debit_minor,
    CASE WHEN d.kind='bill' THEN d.total_minor ELSE 0 END AS credit_minor
   FROM accounts WHERE role=CASE WHEN d.kind='invoice' THEN 'accounts_receivable' ELSE 'accounts_payable' END
   UNION ALL
   SELECT account_id,d.fund_id,CASE WHEN d.kind='bill' THEN amount_minor ELSE 0 END,
    CASE WHEN d.kind='invoice' THEN amount_minor ELSE 0 END FROM document_lines WHERE document_id=did AND amount_minor>0),
  expected AS(SELECT account_id,fund_id,sum(debit_minor) AS debit_minor,sum(credit_minor) AS credit_minor FROM expected_lines GROUP BY account_id,fund_id),
  actual AS(SELECT account_id,fund_id,sum(debit_minor) AS debit_minor,sum(credit_minor) AS credit_minor FROM journal_lines WHERE entry_id=d.posted_entry_id GROUP BY account_id,fund_id)
  (SELECT * FROM expected EXCEPT SELECT * FROM actual) UNION ALL (SELECT * FROM actual EXCEPT SELECT * FROM expected))
 THEN RAISE EXCEPTION 'Document journal accounts, funds and amounts must match its lines and control account' USING ERRCODE='23514'; END IF;
 IF d.status='void' AND d.posted_entry_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM journal_entries WHERE id=d.void_entry_id AND reverses_id=d.posted_entry_id)
 THEN RAISE EXCEPTION 'Voiding a posted document requires its matching reversal' USING ERRCODE='23514'; END IF;
 RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER accounting_document_complete AFTER INSERT OR UPDATE ON accounting.documents DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION accounting.check_document();
CREATE CONSTRAINT TRIGGER accounting_document_lines_complete AFTER INSERT ON accounting.document_lines DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION accounting.check_document();

CREATE FUNCTION accounting.check_payment() RETURNS trigger LANGUAGE plpgsql SET search_path=accounting,pg_temp AS $$
DECLARE d documents%ROWTYPE; e journal_entries%ROWTYPE; control_id bigint;
BEGIN
 SELECT * INTO d FROM documents WHERE id=NEW.document_id;
 SELECT * INTO e FROM journal_entries WHERE id=NEW.entry_id;
 SELECT id INTO control_id FROM accounts WHERE role=CASE WHEN d.kind='invoice' THEN 'accounts_receivable' ELSE 'accounts_payable' END;
 IF e.source<>d.kind||'_payment' OR e.source_ref IS DISTINCT FROM NEW.id::text OR e.total_minor<>NEW.amount_minor
 OR e.entry_date<>NEW.payment_date OR e.currency<>d.currency OR (SELECT count(*) FROM journal_lines WHERE entry_id=e.id)<>2
 OR NOT EXISTS(SELECT 1 FROM journal_lines WHERE entry_id=e.id AND account_id=NEW.cash_account_id AND fund_id=d.fund_id
  AND debit_minor=CASE WHEN d.kind='invoice' THEN NEW.amount_minor ELSE 0 END
  AND credit_minor=CASE WHEN d.kind='bill' THEN NEW.amount_minor ELSE 0 END)
 OR NOT EXISTS(SELECT 1 FROM journal_lines WHERE entry_id=e.id AND account_id=control_id AND fund_id=d.fund_id
  AND debit_minor=CASE WHEN d.kind='bill' THEN NEW.amount_minor ELSE 0 END
  AND credit_minor=CASE WHEN d.kind='invoice' THEN NEW.amount_minor ELSE 0 END)
 THEN RAISE EXCEPTION 'Payment must match its own dated cash and control-account posting' USING ERRCODE='23514'; END IF;
 RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER accounting_payment_complete AFTER INSERT ON accounting.payments DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION accounting.check_payment();
