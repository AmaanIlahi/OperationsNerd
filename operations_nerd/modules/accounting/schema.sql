CREATE TABLE accounting.settings(
 singleton boolean PRIMARY KEY DEFAULT true CHECK(singleton),business_key text NOT NULL,currency text NOT NULL CHECK(currency='USD'));
CREATE TABLE accounting.command_requests(
 idempotency_key text PRIMARY KEY,operation text NOT NULL,payload jsonb NOT NULL,result jsonb NOT NULL,created_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE accounting.accounts(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,code text NOT NULL UNIQUE CHECK(length(code)>0),
 name text NOT NULL CHECK(length(name)>0),account_type text NOT NULL CHECK(account_type IN('asset','liability','equity','income','expense')),
 role text,is_capital boolean NOT NULL,is_active boolean NOT NULL DEFAULT true,
 CHECK(NOT is_capital OR account_type='asset'),
 CHECK(role IS NULL OR role IN('cash','accounts_receivable','accounts_payable','inventory','capital','equity','donor_restricted','unrestricted_net_assets','interfund_clearing','revenue','grant_revenue','expense','cost_of_goods')),
 CHECK(role IS NULL OR (role IN('cash','accounts_receivable','inventory','interfund_clearing') AND account_type='asset' AND NOT is_capital)
 OR(role='capital' AND account_type='asset' AND is_capital) OR(role='accounts_payable' AND account_type='liability')
 OR(role IN('equity','donor_restricted','unrestricted_net_assets') AND account_type='equity')
 OR(role IN('revenue','grant_revenue') AND account_type='income') OR(role IN('expense','cost_of_goods') AND account_type='expense')));
CREATE UNIQUE INDEX accounting_account_names ON accounting.accounts(lower(name));
CREATE UNIQUE INDEX accounting_account_control_roles ON accounting.accounts(role)
 WHERE role IN('accounts_receivable','accounts_payable','donor_restricted','unrestricted_net_assets','interfund_clearing');
CREATE TABLE accounting.funds(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,code text NOT NULL UNIQUE,name text NOT NULL,purpose text,
 restriction_type text NOT NULL CHECK(restriction_type IN('unrestricted','temporarily_restricted','permanently_restricted')),
 is_default boolean NOT NULL DEFAULT false,is_active boolean NOT NULL DEFAULT true,
 CHECK(NOT is_default OR restriction_type='unrestricted'),CHECK(NOT is_default OR is_active));
CREATE UNIQUE INDEX accounting_fund_names ON accounting.funds(lower(name));
CREATE UNIQUE INDEX accounting_default_fund ON accounting.funds(is_default) WHERE is_default;
CREATE TABLE accounting.journal_entries(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,entry_date date NOT NULL,memo text NOT NULL CHECK(length(memo)>0),
 source text NOT NULL CHECK(source IN('manual','invoice','bill','invoice_payment','bill_payment','grant_receipt','fund_release','reversal')),
 source_ref text,currency text NOT NULL CHECK(currency='USD'),total_minor bigint NOT NULL CHECK(total_minor>0 AND total_minor<=10000000000000),
 reverses_id bigint UNIQUE REFERENCES accounting.journal_entries(id),actor_id bigint NOT NULL,
 request_key text NOT NULL REFERENCES accounting.command_requests(idempotency_key) DEFERRABLE INITIALLY DEFERRED,
 created_at timestamptz NOT NULL DEFAULT now(),created_txid bigint NOT NULL DEFAULT txid_current(),
 CHECK((source='reversal')=(reverses_id IS NOT NULL)),UNIQUE(source,source_ref));
CREATE TABLE accounting.journal_lines(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,entry_id bigint NOT NULL REFERENCES accounting.journal_entries(id),
 line_no integer NOT NULL CHECK(line_no>0),account_id bigint NOT NULL REFERENCES accounting.accounts(id),
 fund_id bigint NOT NULL REFERENCES accounting.funds(id),debit_minor bigint NOT NULL DEFAULT 0 CHECK(debit_minor>=0 AND debit_minor<=10000000000000),
 credit_minor bigint NOT NULL DEFAULT 0 CHECK(credit_minor>=0 AND credit_minor<=10000000000000),
 CHECK((debit_minor>0)<>(credit_minor>0)),UNIQUE(entry_id,line_no));
CREATE INDEX accounting_journal_dates ON accounting.journal_entries(entry_date,id);
CREATE INDEX accounting_journal_accounts ON accounting.journal_lines(account_id,entry_id);
CREATE INDEX accounting_journal_funds ON accounting.journal_lines(fund_id,entry_id);
CREATE TABLE accounting.documents(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,kind text NOT NULL CHECK(kind IN('invoice','bill')),
 number text NOT NULL CHECK(length(number)>0),party_entity_key text NOT NULL,party_record_id bigint NOT NULL REFERENCES core.entities(id),
 party_snapshot jsonb NOT NULL,issue_date date NOT NULL,due_date date NOT NULL CHECK(due_date>=issue_date),
 currency text NOT NULL CHECK(currency='USD'),fund_id bigint NOT NULL REFERENCES accounting.funds(id),
 status text NOT NULL DEFAULT 'draft' CHECK(status IN('draft','posted','void')),
 total_minor bigint NOT NULL CHECK(total_minor>0 AND total_minor<=10000000000000),
 posted_entry_id bigint UNIQUE REFERENCES accounting.journal_entries(id),void_entry_id bigint UNIQUE REFERENCES accounting.journal_entries(id),
 actor_id bigint NOT NULL,request_key text NOT NULL REFERENCES accounting.command_requests(idempotency_key) DEFERRABLE INITIALLY DEFERRED,
 created_at timestamptz NOT NULL DEFAULT now(),created_txid bigint NOT NULL DEFAULT txid_current(),
 CHECK(status!='posted' OR posted_entry_id IS NOT NULL),CHECK(void_entry_id IS NULL OR status='void'),
 UNIQUE(kind,party_record_id,number));
CREATE TABLE accounting.document_lines(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,document_id bigint NOT NULL REFERENCES accounting.documents(id),
 line_no integer NOT NULL CHECK(line_no>0),description text NOT NULL CHECK(length(description)>0),
 quantity bigint NOT NULL CHECK(quantity>0 AND quantity<=1000000),unit_price_minor bigint NOT NULL CHECK(unit_price_minor>=0 AND unit_price_minor<=10000000000000),
 amount_minor bigint NOT NULL CHECK(amount_minor>=0 AND amount_minor<=10000000000000),account_id bigint NOT NULL REFERENCES accounting.accounts(id),
 CHECK(quantity*unit_price_minor=amount_minor),UNIQUE(document_id,line_no));
CREATE TABLE accounting.payments(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,document_id bigint NOT NULL REFERENCES accounting.documents(id),
 amount_minor bigint NOT NULL CHECK(amount_minor>0 AND amount_minor<=10000000000000),cash_account_id bigint NOT NULL REFERENCES accounting.accounts(id),
 payment_date date NOT NULL,reference text NOT NULL CHECK(length(reference)>0),entry_id bigint NOT NULL UNIQUE REFERENCES accounting.journal_entries(id),
 actor_id bigint NOT NULL,request_key text NOT NULL REFERENCES accounting.command_requests(idempotency_key) DEFERRABLE INITIALLY DEFERRED,
 created_at timestamptz NOT NULL DEFAULT now());

