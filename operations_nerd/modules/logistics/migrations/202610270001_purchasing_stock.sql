-- One private business database. Core bindings are adapter references, not catalogs.
CREATE SCHEMA IF NOT EXISTS logistics;
SET search_path TO logistics, public;
CREATE TABLE IF NOT EXISTS schema_migrations (
 version text PRIMARY KEY, checksum text NOT NULL,
 applied_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE database_identity (
 singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
 business_key text NOT NULL CHECK (length(business_key)>0)
);
CREATE TABLE command_requests (
 idempotency_key text PRIMARY KEY CHECK(length(idempotency_key)>0),
 operation text NOT NULL CHECK(length(operation)>0),
 payload jsonb NOT NULL,
 result jsonb,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE core_bindings (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 kind text NOT NULL CHECK(kind IN ('supplier','customer','item','location','carrier','actor')),
 external_key text NOT NULL CHECK(length(external_key)>0),
 snapshot jsonb NOT NULL DEFAULT '{}'::jsonb,
 valid_from timestamptz NOT NULL DEFAULT now(), valid_to timestamptz,
 UNIQUE(kind,external_key,valid_from), CHECK(valid_to IS NULL OR valid_to>valid_from)
);
CREATE UNIQUE INDEX core_bindings_current ON core_bindings(kind,external_key) WHERE valid_to IS NULL;
CREATE TABLE demand_lines (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 external_key text NOT NULL UNIQUE CHECK(length(external_key)>0),
 order_ref text NOT NULL CHECK(length(order_ref)>0),
 item_id bigint NOT NULL REFERENCES core_bindings(id),
 quantity bigint NOT NULL CHECK(quantity>0), currency text NOT NULL CHECK(currency ~ '^[A-Z]{3}$'),
 budget_minor bigint CHECK(budget_minor>=0), required_by date,
 UNIQUE(id,item_id)
);

CREATE TABLE quote_versions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 quote_ref text NOT NULL CHECK(length(quote_ref)>0),version integer NOT NULL CHECK(version>0),
 supplier_id bigint NOT NULL REFERENCES core_bindings(id),item_id bigint NOT NULL REFERENCES core_bindings(id),
 quantity_priced bigint NOT NULL CHECK(quantity_priced>0),capacity_quantity bigint NOT NULL CHECK(capacity_quantity>=0),
 price_minor bigint NOT NULL CHECK(price_minor>=0),pricing_kind text NOT NULL CHECK(pricing_kind IN ('unit','total')),
 currency text NOT NULL CHECK(currency ~ '^[A-Z]{3}$'),source text NOT NULL CHECK(source IN ('supplier','synthetic','ai_estimate')),
 generated_at timestamptz NOT NULL DEFAULT now(),expires_at timestamptz NOT NULL,
 expected_date date NOT NULL,supersedes_id bigint REFERENCES quote_versions(id),
 UNIQUE(quote_ref,version),CHECK(expires_at>generated_at)
);
CREATE TABLE purchase_orders (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 supplier_id bigint NOT NULL REFERENCES core_bindings(id),currency text NOT NULL CHECK(currency ~ '^[A-Z]{3}$'),
 status text NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','approved')),version integer NOT NULL DEFAULT 1 CHECK(version>0),
 created_at timestamptz NOT NULL DEFAULT now(),approved_at timestamptz,approved_by bigint REFERENCES core_bindings(id),
 approved_supplier_snapshot jsonb,total_minor bigint CHECK(total_minor>=0),
 CHECK((status='approved')=(approved_at IS NOT NULL AND approved_by IS NOT NULL AND approved_supplier_snapshot IS NOT NULL AND total_minor IS NOT NULL))
);
CREATE TABLE purchase_order_lines (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 purchase_order_id bigint NOT NULL REFERENCES purchase_orders(id),quote_version_id bigint NOT NULL UNIQUE REFERENCES quote_versions(id),
 item_id bigint NOT NULL REFERENCES core_bindings(id),quantity bigint NOT NULL CHECK(quantity>0),approved_terms jsonb
);
CREATE TABLE purchase_allocations (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 po_line_id bigint NOT NULL REFERENCES purchase_order_lines(id),demand_line_id bigint NOT NULL REFERENCES demand_lines(id),
 quantity bigint NOT NULL CHECK(quantity>0),cost_share_minor bigint CHECK(cost_share_minor>=0),UNIQUE(po_line_id,demand_line_id)
);

CREATE TABLE stock_resources (
 item_id bigint NOT NULL REFERENCES core_bindings(id),
 location_id bigint NOT NULL REFERENCES core_bindings(id), PRIMARY KEY(item_id,location_id)
);
CREATE TABLE stock_lot_tracking (item_id bigint PRIMARY KEY REFERENCES core_bindings(id));
CREATE TABLE stock_lots (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 item_id bigint NOT NULL REFERENCES stock_lot_tracking(item_id),
 lot_number text NOT NULL CHECK(length(lot_number)>0), expiry_date date,
 created_at timestamptz NOT NULL DEFAULT now(), UNIQUE(item_id,lot_number), UNIQUE(item_id,id)
);
CREATE TABLE stock_lot_holds (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lot_id bigint NOT NULL REFERENCES stock_lots(id),
 event text NOT NULL CHECK(event IN ('hold','release')),
 reason text NOT NULL CHECK(length(reason)>0), request_key text NOT NULL REFERENCES command_requests(idempotency_key) DEFERRABLE INITIALLY DEFERRED,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE receipts (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 delivery_ref text NOT NULL UNIQUE CHECK(length(delivery_ref)>0),
 request_key text NOT NULL REFERENCES command_requests(idempotency_key) DEFERRABLE INITIALLY DEFERRED,
 received_on date NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE receipt_lines (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 receipt_id bigint NOT NULL REFERENCES receipts(id), line_number integer NOT NULL CHECK(line_number>0),
 po_line_id bigint REFERENCES purchase_order_lines(id),
 item_id bigint NOT NULL REFERENCES core_bindings(id), location_id bigint NOT NULL REFERENCES core_bindings(id),
 quantity bigint NOT NULL CHECK(quantity>0), source_ref text NOT NULL CHECK(length(source_ref)>0),
 lot_id bigint, UNIQUE(receipt_id,line_number), UNIQUE(id,item_id,location_id),
 FOREIGN KEY(item_id,lot_id) REFERENCES stock_lots(item_id,id)
);
CREATE TABLE stock_reservations (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 item_id bigint NOT NULL REFERENCES core_bindings(id), location_id bigint NOT NULL REFERENCES core_bindings(id),
 order_ref text NOT NULL CHECK(length(order_ref)>0), demand_line_id bigint REFERENCES demand_lines(id),
 quantity bigint NOT NULL CHECK(quantity>0), quantity_shipped bigint NOT NULL DEFAULT 0 CHECK(quantity_shipped>=0 AND quantity_shipped<=quantity),
 status text NOT NULL DEFAULT 'active' CHECK(status IN ('active','fulfilled','released')),
 request_key text NOT NULL REFERENCES command_requests(idempotency_key) DEFERRABLE INITIALLY DEFERRED,
 created_at timestamptz NOT NULL DEFAULT now(),
 CHECK((status='fulfilled')=(quantity_shipped=quantity)), UNIQUE(id,item_id,location_id)
);
CREATE TABLE lot_allocations (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reservation_id bigint NOT NULL REFERENCES stock_reservations(id),
 item_id bigint NOT NULL, lot_id bigint NOT NULL,
 quantity bigint NOT NULL CHECK(quantity>0), as_of date NOT NULL,
 FOREIGN KEY(item_id,lot_id) REFERENCES stock_lots(item_id,id), UNIQUE(reservation_id,lot_id)
);
CREATE TABLE receipt_allocations (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 receipt_line_id bigint NOT NULL REFERENCES receipt_lines(id),
 purchase_allocation_id bigint REFERENCES purchase_allocations(id),
 demand_line_id bigint REFERENCES demand_lines(id),
 reservation_id bigint NOT NULL UNIQUE REFERENCES stock_reservations(id),
 quantity bigint NOT NULL CHECK(quantity>0),
 CHECK(purchase_allocation_id IS NULL OR demand_line_id IS NOT NULL)
);
CREATE TABLE shipments (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 shipment_number text NOT NULL UNIQUE CHECK(length(shipment_number)>0), order_ref text,
 request_key text NOT NULL REFERENCES command_requests(idempotency_key) DEFERRABLE INITIALLY DEFERRED,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE shipment_lines (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 shipment_id bigint NOT NULL REFERENCES shipments(id), reservation_id bigint NOT NULL REFERENCES stock_reservations(id),
 quantity bigint NOT NULL CHECK(quantity>0), UNIQUE(shipment_id,reservation_id), UNIQUE(shipment_id,id,reservation_id)
);
CREATE TABLE shipment_dispatches (
 shipment_id bigint PRIMARY KEY REFERENCES shipments(id),
 carrier text NOT NULL CHECK(length(carrier)>0), label_ref text CHECK(length(label_ref)>0), tracking_ref text CHECK(length(tracking_ref)>0),
 as_of date NOT NULL, request_key text NOT NULL REFERENCES command_requests(idempotency_key) DEFERRABLE INITIALLY DEFERRED,
 CHECK(label_ref IS NOT NULL OR tracking_ref IS NOT NULL)
);
CREATE TABLE shipment_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 shipment_id bigint NOT NULL REFERENCES shipment_dispatches(shipment_id),
 event text NOT NULL CHECK(event IN ('in_transit','out_for_delivery','delivery_failed','delivered','exception')),
 occurred_at timestamptz NOT NULL, detail text,
 request_key text NOT NULL REFERENCES command_requests(idempotency_key) DEFERRABLE INITIALLY DEFERRED,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE stock_movements (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 item_id bigint NOT NULL REFERENCES core_bindings(id), location_id bigint NOT NULL REFERENCES core_bindings(id),
 quantity bigint NOT NULL, movement_type text NOT NULL,
 reservation_id bigint REFERENCES stock_reservations(id),
 lot_id bigint, as_of date,
 receipt_line_id bigint UNIQUE REFERENCES receipt_lines(id), shipment_id bigint, shipment_line_id bigint,
 source_ref text NOT NULL CHECK(length(source_ref)>0),
 request_key text NOT NULL REFERENCES command_requests(idempotency_key) DEFERRABLE INITIALLY DEFERRED,
 created_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(item_id,lot_id) REFERENCES stock_lots(item_id,id),
 FOREIGN KEY(reservation_id,lot_id) REFERENCES lot_allocations(reservation_id,lot_id),
 FOREIGN KEY(shipment_id,shipment_line_id,reservation_id) REFERENCES shipment_lines(shipment_id,id,reservation_id),
 FOREIGN KEY(shipment_id) REFERENCES shipment_dispatches(shipment_id) DEFERRABLE INITIALLY DEFERRED,
 CHECK((movement_type IN ('receipt','opening') AND quantity>0) OR (movement_type='shipment' AND quantity<0)),
 CHECK((movement_type='shipment')=(reservation_id IS NOT NULL)),
 CHECK((movement_type='receipt')=(receipt_line_id IS NOT NULL)),
 CHECK(movement_type<>'shipment' OR lot_id IS NULL OR as_of IS NOT NULL),
 CHECK((shipment_id IS NULL)=(shipment_line_id IS NULL)),
 CHECK(shipment_line_id IS NULL OR movement_type='shipment')
);
