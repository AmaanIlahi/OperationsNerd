CREATE FUNCTION guard_receipt_line() RETURNS trigger LANGUAGE plpgsql SET search_path=logistics,pg_temp AS $$
DECLARE p purchase_order_lines%ROWTYPE; stat text; received bigint;
BEGIN
 IF NEW.po_line_id IS NOT NULL THEN
  SELECT * INTO p FROM purchase_order_lines WHERE id=NEW.po_line_id FOR UPDATE;
  SELECT status INTO stat FROM purchase_orders WHERE id=p.purchase_order_id;
  IF stat<>'approved' OR p.item_id<>NEW.item_id OR NEW.source_ref<>p.id::text THEN RAISE EXCEPTION 'receipt must reference matching approved purchase line' USING ERRCODE='23514'; END IF;
  SELECT COALESCE(sum(quantity),0)::bigint INTO received FROM receipt_lines WHERE po_line_id=NEW.po_line_id;
  IF received+NEW.quantity>p.quantity THEN RAISE EXCEPTION 'receipt exceeds purchase line quantity' USING ERRCODE='23514'; END IF;
 END IF;
 PERFORM lock_stock_resource(NEW.item_id,NEW.location_id);
 RETURN NEW;
END; $$;
CREATE TRIGGER receipt_line_guard BEFORE INSERT ON receipt_lines FOR EACH ROW EXECUTE FUNCTION guard_receipt_line();
CREATE FUNCTION guard_receipt_allocation() RETURNS trigger LANGUAGE plpgsql SET search_path=logistics,pg_temp AS $$
DECLARE p purchase_allocations%ROWTYPE; l receipt_lines%ROWTYPE; r stock_reservations%ROWTYPE; total bigint;
BEGIN
 SELECT * INTO l FROM receipt_lines WHERE id=NEW.receipt_line_id FOR UPDATE;
 IF NEW.purchase_allocation_id IS NOT NULL THEN
  SELECT * INTO p FROM purchase_allocations WHERE id=NEW.purchase_allocation_id FOR UPDATE;
  IF p.po_line_id<>l.po_line_id OR p.demand_line_id<>NEW.demand_line_id THEN RAISE EXCEPTION 'receipt allocation link mismatch' USING ERRCODE='23514'; END IF;
  SELECT COALESCE(sum(quantity),0)::bigint INTO total FROM receipt_allocations WHERE purchase_allocation_id=p.id;
  IF total+NEW.quantity>p.quantity THEN RAISE EXCEPTION 'receipt exceeds purchase allocation' USING ERRCODE='23514'; END IF;
 END IF;
 SELECT * INTO r FROM stock_reservations WHERE id=NEW.reservation_id;
 IF r.request_key<>(SELECT request_key FROM receipts WHERE id=l.receipt_id) THEN RAISE EXCEPTION 'receipt reservation must share its delivery command' USING ERRCODE='23514'; END IF;
 IF l.lot_id IS NOT NULL AND (EXISTS(SELECT 1 FROM lot_allocations WHERE reservation_id=r.id AND lot_id<>l.lot_id) OR NOT EXISTS(SELECT 1 FROM lot_allocations WHERE reservation_id=r.id AND lot_id=l.lot_id AND quantity=NEW.quantity)) THEN RAISE EXCEPTION 'receipt reservation must use the received lot' USING ERRCODE='23514'; END IF;
 IF (r.item_id,r.location_id,r.quantity,r.demand_line_id) IS DISTINCT FROM (l.item_id,l.location_id,NEW.quantity,NEW.demand_line_id) THEN RAISE EXCEPTION 'receipt reservation mismatch' USING ERRCODE='23514'; END IF;
 SELECT COALESCE(sum(quantity),0)::bigint INTO total FROM receipt_allocations WHERE receipt_line_id=l.id;
 IF total+NEW.quantity>l.quantity THEN RAISE EXCEPTION 'receipt allocations exceed physical receipt quantity' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END; $$;
CREATE TRIGGER receipt_allocation_guard BEFORE INSERT ON receipt_allocations FOR EACH ROW EXECUTE FUNCTION guard_receipt_allocation();
