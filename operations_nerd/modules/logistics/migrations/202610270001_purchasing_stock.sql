CREATE VIEW stock_levels AS
 SELECT r.item_id,r.location_id,
 (SELECT COALESCE(sum(m.quantity),0)::bigint FROM stock_movements m WHERE m.item_id=r.item_id AND m.location_id=r.location_id) AS on_hand,
 (SELECT COALESCE(sum(s.quantity-s.quantity_shipped),0)::bigint FROM stock_reservations s WHERE s.item_id=r.item_id AND s.location_id=r.location_id AND s.status='active') AS reserved
 FROM stock_resources r;
CREATE VIEW stock_lot_levels AS
 SELECT l.id AS lot_id,l.item_id,l.lot_number,l.expiry_date,
 (SELECT COALESCE(sum(m.quantity),0)::bigint FROM stock_movements m WHERE m.lot_id=l.id) AS on_hand,
 (SELECT COALESCE(sum(a.quantity),0)::bigint FROM lot_allocations a JOIN stock_reservations r ON r.id=a.reservation_id WHERE a.lot_id=l.id AND r.status='active')
 +(SELECT COALESCE(sum(m.quantity),0)::bigint FROM stock_movements m JOIN stock_reservations r ON r.id=m.reservation_id WHERE m.lot_id=l.id AND r.status='active') AS allocated,
 COALESCE((SELECT h.event='hold' FROM stock_lot_holds h WHERE h.lot_id=l.id ORDER BY h.id DESC LIMIT 1),false) AS on_hold
 FROM stock_lots l;
CREATE VIEW shipment_status AS
 SELECT s.id AS shipment_id,s.shipment_number,s.order_ref,
 CASE WHEN EXISTS(SELECT 1 FROM shipment_events e WHERE e.shipment_id=s.id AND e.event='delivered') THEN 'delivered'
 WHEN d.shipment_id IS NULL THEN 'draft'
 WHEN (SELECT e.event FROM shipment_events e WHERE e.shipment_id=s.id ORDER BY e.occurred_at DESC,e.id DESC LIMIT 1) IN ('exception','delivery_failed') THEN 'exception'
 WHEN EXISTS(SELECT 1 FROM shipment_events e WHERE e.shipment_id=s.id) THEN 'in_transit'
 ELSE 'dispatched' END AS status,
 d.carrier,d.label_ref,d.tracking_ref,d.as_of AS dispatched_on
 FROM shipments s LEFT JOIN shipment_dispatches d ON d.shipment_id=s.id;

CREATE VIEW demand_fulfillment AS
 SELECT d.id AS demand_line_id,d.external_key,d.order_ref,d.item_id,d.quantity,
 COALESCE(x.reserved,0)::bigint AS reserved,COALESCE(x.shipped,0)::bigint AS shipped,
 COALESCE(y.delivered,0)::bigint AS delivered,
 CASE WHEN COALESCE(y.delivered,0)>=d.quantity THEN 'delivered'
 WHEN COALESCE(x.shipped,0)>=d.quantity THEN 'shipped'
 WHEN COALESCE(x.reserved,0)+COALESCE(x.shipped,0)>=d.quantity THEN 'allocated'
 ELSE 'received' END AS status
 FROM demand_lines d
 LEFT JOIN LATERAL (SELECT sum(CASE WHEN r.status='active' THEN r.quantity-r.quantity_shipped ELSE 0 END) AS reserved,sum(r.quantity_shipped) AS shipped FROM stock_reservations r WHERE r.demand_line_id=d.id) x ON true
 LEFT JOIN LATERAL (SELECT -sum(m.quantity) AS delivered FROM stock_movements m JOIN stock_reservations r ON r.id=m.reservation_id WHERE r.demand_line_id=d.id AND m.movement_type='shipment' AND EXISTS(SELECT 1 FROM shipment_events e WHERE e.shipment_id=m.shipment_id AND e.event='delivered')) y ON true;

CREATE FUNCTION reject_mutation() RETURNS trigger LANGUAGE plpgsql SET search_path=logistics,pg_temp AS $$
 BEGIN RAISE EXCEPTION '% rows are immutable',TG_TABLE_NAME USING ERRCODE='23514'; END;
$$;
CREATE FUNCTION lock_stock_resource(i bigint,l bigint) RETURNS void LANGUAGE plpgsql SET search_path=logistics,pg_temp AS $$
BEGIN
 -- Item-level lock also serializes enabling lots and changing holds across locations.
 PERFORM pg_advisory_xact_lock(i);
 IF NOT EXISTS(SELECT 1 FROM core_bindings WHERE id=i AND kind='item') THEN RAISE EXCEPTION 'invalid item binding' USING ERRCODE='23514'; END IF;
 IF NOT EXISTS(SELECT 1 FROM core_bindings WHERE id=l AND kind='location') THEN RAISE EXCEPTION 'invalid location binding' USING ERRCODE='23514'; END IF;
 INSERT INTO stock_resources(item_id,location_id) VALUES(i,l) ON CONFLICT DO NOTHING;
 PERFORM 1 FROM stock_resources WHERE item_id=i AND location_id=l FOR UPDATE;
END; $$;
CREATE FUNCTION guard_lot_tracking() RETURNS trigger LANGUAGE plpgsql SET search_path=logistics,pg_temp AS $$
BEGIN
 PERFORM pg_advisory_xact_lock(NEW.item_id);
 IF NOT EXISTS(SELECT 1 FROM core_bindings WHERE id=NEW.item_id AND kind='item') THEN RAISE EXCEPTION 'invalid item binding' USING ERRCODE='23514'; END IF;
 IF EXISTS(SELECT 1 FROM stock_movements WHERE item_id=NEW.item_id) THEN RAISE EXCEPTION 'item already has stock without lots' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END; $$;
CREATE TRIGGER lot_tracking_guard BEFORE INSERT ON stock_lot_tracking FOR EACH ROW EXECUTE FUNCTION guard_lot_tracking();
CREATE FUNCTION guard_lot_hold() RETURNS trigger LANGUAGE plpgsql SET search_path=logistics,pg_temp AS $$
DECLARE i bigint; prior text;
BEGIN
 SELECT item_id INTO i FROM stock_lots WHERE id=NEW.lot_id;
 PERFORM pg_advisory_xact_lock(i);
 SELECT event INTO prior FROM stock_lot_holds WHERE lot_id=NEW.lot_id ORDER BY id DESC LIMIT 1;
 IF NEW.event=COALESCE(prior,'release') THEN RAISE EXCEPTION 'lot holds must alternate' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END; $$;
CREATE TRIGGER lot_hold_guard BEFORE INSERT ON stock_lot_holds FOR EACH ROW EXECUTE FUNCTION guard_lot_hold();

CREATE FUNCTION guard_reservation() RETURNS trigger LANGUAGE plpgsql SET search_path=logistics,pg_temp AS $$
DECLARE level_on_hand bigint; level_reserved bigint; actual_shipped bigint; demand_limit bigint; demand_used bigint;
BEGIN
 IF TG_OP='INSERT' AND NEW.demand_line_id IS NOT NULL THEN
  SELECT quantity INTO demand_limit FROM demand_lines WHERE id=NEW.demand_line_id FOR UPDATE;
  SELECT COALESCE(sum(CASE WHEN status='active' THEN quantity ELSE quantity_shipped END),0)::bigint INTO demand_used FROM stock_reservations WHERE demand_line_id=NEW.demand_line_id;
  IF NEW.quantity+demand_used>demand_limit THEN RAISE EXCEPTION 'reservation exceeds customer demand' USING ERRCODE='23514'; END IF;
 END IF;
 PERFORM lock_stock_resource(NEW.item_id,NEW.location_id);
 IF TG_OP='INSERT' THEN
  IF NEW.status<>'active' OR NEW.quantity_shipped<>0 THEN RAISE EXCEPTION 'reservation starts active with nothing shipped' USING ERRCODE='23514'; END IF;
  SELECT on_hand,reserved INTO level_on_hand,level_reserved FROM stock_levels WHERE item_id=NEW.item_id AND location_id=NEW.location_id;
  IF NEW.quantity+level_reserved>level_on_hand THEN RAISE EXCEPTION 'reservation exceeds available stock' USING ERRCODE='23514'; END IF;
  IF NEW.demand_line_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM demand_lines WHERE id=NEW.demand_line_id AND item_id=NEW.item_id AND external_key=NEW.order_ref) THEN RAISE EXCEPTION 'reservation demand mismatch' USING ERRCODE='23514'; END IF;
 ELSE
  IF OLD.status<>'active' THEN RAISE EXCEPTION 'reservation is no longer active' USING ERRCODE='23514'; END IF;
  IF (NEW.id,NEW.item_id,NEW.location_id,NEW.order_ref,NEW.demand_line_id,NEW.quantity,NEW.request_key,NEW.created_at) IS DISTINCT FROM (OLD.id,OLD.item_id,OLD.location_id,OLD.order_ref,OLD.demand_line_id,OLD.quantity,OLD.request_key,OLD.created_at) THEN RAISE EXCEPTION 'reservation identity and quantity are frozen' USING ERRCODE='23514'; END IF;
  SELECT COALESCE(-sum(quantity),0)::bigint INTO actual_shipped FROM stock_movements WHERE reservation_id=NEW.id;
  IF NEW.quantity_shipped<>actual_shipped THEN RAISE EXCEPTION 'shipped quantity must match ledger' USING ERRCODE='23514'; END IF;
 END IF;
 RETURN NEW;
END; $$;
CREATE TRIGGER reservation_guard BEFORE INSERT OR UPDATE ON stock_reservations FOR EACH ROW EXECUTE FUNCTION guard_reservation();
CREATE TRIGGER reservation_no_delete BEFORE DELETE ON stock_reservations FOR EACH ROW EXECUTE FUNCTION reject_mutation();
CREATE FUNCTION guard_lot_allocation() RETURNS trigger LANGUAGE plpgsql SET search_path=logistics,pg_temp AS $$
DECLARE r stock_reservations%ROWTYPE; l stock_lot_levels%ROWTYPE; loc_on_hand bigint; loc_allocated bigint;
BEGIN
 SELECT * INTO r FROM stock_reservations WHERE id=NEW.reservation_id;
 PERFORM lock_stock_resource(NEW.item_id,r.location_id);
 IF r.item_id<>NEW.item_id OR r.status<>'active' THEN RAISE EXCEPTION 'lot allocation reservation mismatch' USING ERRCODE='23514'; END IF;
 SELECT * INTO l FROM stock_lot_levels WHERE lot_id=NEW.lot_id;
 IF l.on_hold OR NEW.as_of>l.expiry_date THEN RAISE EXCEPTION 'cannot allocate held or expired lot' USING ERRCODE='23514'; END IF;
 SELECT COALESCE(sum(quantity),0)::bigint INTO loc_on_hand FROM stock_movements WHERE lot_id=NEW.lot_id AND location_id=r.location_id;
 SELECT COALESCE(sum(a.quantity),0)::bigint INTO loc_allocated FROM lot_allocations a JOIN stock_reservations z ON z.id=a.reservation_id WHERE a.lot_id=NEW.lot_id AND z.location_id=r.location_id AND z.status='active';
 loc_allocated:=loc_allocated+(SELECT COALESCE(sum(m.quantity),0)::bigint FROM stock_movements m JOIN stock_reservations z ON z.id=m.reservation_id WHERE m.lot_id=NEW.lot_id AND z.location_id=r.location_id AND z.status='active');
 IF NEW.quantity>loc_on_hand-loc_allocated THEN RAISE EXCEPTION 'allocation exceeds free lot stock' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END; $$;
CREATE TRIGGER lot_allocation_guard BEFORE INSERT ON lot_allocations FOR EACH ROW EXECUTE FUNCTION guard_lot_allocation();
CREATE FUNCTION check_reservation_lots() RETURNS trigger LANGUAGE plpgsql SET search_path=logistics,pg_temp AS $$
DECLARE rid bigint; r stock_reservations%ROWTYPE; q bigint;
BEGIN
 IF TG_TABLE_NAME='stock_reservations' THEN rid:=NEW.id; ELSE rid:=NEW.reservation_id; END IF;
 SELECT * INTO r FROM stock_reservations WHERE id=rid;
 SELECT COALESCE(sum(quantity),0)::bigint INTO q FROM lot_allocations WHERE reservation_id=rid AND item_id=r.item_id;
 IF q<>(CASE WHEN EXISTS(SELECT 1 FROM stock_lot_tracking WHERE item_id=r.item_id) THEN r.quantity ELSE 0 END) THEN RAISE EXCEPTION 'lot allocations must match reservation quantity' USING ERRCODE='23514'; END IF;
 RETURN NULL;
END; $$;
CREATE CONSTRAINT TRIGGER reservation_lots_check AFTER INSERT OR UPDATE ON stock_reservations DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_reservation_lots();
CREATE CONSTRAINT TRIGGER allocation_lots_check AFTER INSERT ON lot_allocations DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_reservation_lots();

CREATE FUNCTION guard_movement() RETURNS trigger LANGUAGE plpgsql SET search_path=logistics,pg_temp AS $$
DECLARE r stock_reservations%ROWTYPE; current_hand bigint; lot_hand bigint; lot_free bigint; alloc bigint; sent bigint; l stock_lot_levels%ROWTYPE; rl receipt_lines%ROWTYPE;
BEGIN
 PERFORM lock_stock_resource(NEW.item_id,NEW.location_id);
 IF (NEW.lot_id IS NOT NULL)<>(EXISTS(SELECT 1 FROM stock_lot_tracking WHERE item_id=NEW.item_id)) THEN RAISE EXCEPTION 'movement lot tracking mismatch' USING ERRCODE='23514'; END IF;
 SELECT COALESCE(sum(quantity),0)::bigint INTO current_hand FROM stock_movements WHERE item_id=NEW.item_id AND location_id=NEW.location_id;
 IF current_hand+NEW.quantity<0 THEN RAISE EXCEPTION 'on hand would go negative' USING ERRCODE='23514'; END IF;
 IF NEW.movement_type='opening' AND EXISTS(SELECT 1 FROM stock_movements WHERE item_id=NEW.item_id AND movement_type<>'opening') THEN RAISE EXCEPTION 'opening stock comes first' USING ERRCODE='23514'; END IF;
 IF NEW.receipt_line_id IS NOT NULL THEN
  SELECT * INTO rl FROM receipt_lines WHERE id=NEW.receipt_line_id;
  IF (rl.item_id,rl.location_id,rl.quantity,rl.lot_id,rl.source_ref) IS DISTINCT FROM (NEW.item_id,NEW.location_id,NEW.quantity,NEW.lot_id,NEW.source_ref) THEN RAISE EXCEPTION 'receipt movement mismatch' USING ERRCODE='23514'; END IF;
 END IF;
 IF NEW.reservation_id IS NOT NULL THEN
  SELECT * INTO r FROM stock_reservations WHERE id=NEW.reservation_id FOR UPDATE;
  IF r.status<>'active' OR r.item_id<>NEW.item_id OR r.location_id<>NEW.location_id THEN RAISE EXCEPTION 'shipment reservation mismatch or inactive' USING ERRCODE='23514'; END IF;
  IF -NEW.quantity>r.quantity-r.quantity_shipped THEN RAISE EXCEPTION 'shipment exceeds reservation' USING ERRCODE='23514'; END IF;
 END IF;
 IF NEW.lot_id IS NOT NULL THEN
  SELECT COALESCE(sum(quantity),0)::bigint INTO lot_hand FROM stock_movements WHERE lot_id=NEW.lot_id AND location_id=NEW.location_id;
  IF lot_hand+NEW.quantity<0 THEN RAISE EXCEPTION 'lot on hand would go negative' USING ERRCODE='23514'; END IF;
  IF NEW.movement_type='shipment' THEN
   SELECT * INTO l FROM stock_lot_levels WHERE lot_id=NEW.lot_id;
   IF l.on_hold OR NEW.as_of>l.expiry_date THEN RAISE EXCEPTION 'cannot ship held or expired lot' USING ERRCODE='23514'; END IF;
   SELECT quantity INTO alloc FROM lot_allocations WHERE reservation_id=NEW.reservation_id AND lot_id=NEW.lot_id;
   SELECT COALESCE(-sum(quantity),0)::bigint INTO sent FROM stock_movements WHERE reservation_id=NEW.reservation_id AND lot_id=NEW.lot_id;
   IF -NEW.quantity>alloc-sent THEN RAISE EXCEPTION 'shipment exceeds lot allocation' USING ERRCODE='23514'; END IF;
  END IF;
 END IF;
 IF NEW.shipment_id IS NOT NULL THEN
  IF EXISTS(SELECT 1 FROM shipment_dispatches WHERE shipment_id=NEW.shipment_id) THEN RAISE EXCEPTION 'shipment already dispatched' USING ERRCODE='23514'; END IF;
  SELECT quantity INTO alloc FROM shipment_lines WHERE id=NEW.shipment_line_id;
  SELECT COALESCE(-sum(quantity),0)::bigint INTO sent FROM stock_movements WHERE shipment_line_id=NEW.shipment_line_id;
  IF -NEW.quantity>alloc-sent THEN RAISE EXCEPTION 'movement exceeds shipment line' USING ERRCODE='23514'; END IF;
 END IF;
 RETURN NEW;
END; $$;
CREATE TRIGGER movement_guard BEFORE INSERT ON stock_movements FOR EACH ROW EXECUTE FUNCTION guard_movement();
CREATE FUNCTION post_movement() RETURNS trigger LANGUAGE plpgsql SET search_path=logistics,pg_temp AS $$
BEGIN
 IF NEW.reservation_id IS NOT NULL THEN
  UPDATE stock_reservations SET quantity_shipped=quantity_shipped-NEW.quantity,
  status=CASE WHEN quantity_shipped-NEW.quantity=quantity THEN 'fulfilled' ELSE status END WHERE id=NEW.reservation_id;
 END IF;
 RETURN NULL;
END; $$;
CREATE TRIGGER movement_post AFTER INSERT ON stock_movements FOR EACH ROW EXECUTE FUNCTION post_movement();
CREATE FUNCTION guard_shipment_line() RETURNS trigger LANGUAGE plpgsql SET search_path=logistics,pg_temp AS $$
DECLARE intended text; actual text; reservation_row stock_reservations%ROWTYPE; planned bigint;
BEGIN
 PERFORM pg_advisory_xact_lock(hashtextextended('shipment:' || NEW.shipment_id::text,0));
 PERFORM 1 FROM shipments WHERE id=NEW.shipment_id FOR UPDATE;
 IF EXISTS(SELECT 1 FROM shipment_dispatches WHERE shipment_id=NEW.shipment_id) THEN RAISE EXCEPTION 'cannot add lines after dispatch' USING ERRCODE='23514'; END IF;
 SELECT * INTO reservation_row FROM stock_reservations WHERE id=NEW.reservation_id;
 PERFORM lock_stock_resource(reservation_row.item_id,reservation_row.location_id);
 SELECT * INTO reservation_row FROM stock_reservations WHERE id=NEW.reservation_id;
 SELECT COALESCE(sum(l.quantity),0)::bigint INTO planned FROM shipment_lines l WHERE l.reservation_id=NEW.reservation_id AND NOT EXISTS(SELECT 1 FROM shipment_dispatches d WHERE d.shipment_id=l.shipment_id);
 IF reservation_row.status<>'active' OR NEW.quantity>reservation_row.quantity-reservation_row.quantity_shipped-planned THEN RAISE EXCEPTION 'shipment line exceeds unplanned reservation remainder' USING ERRCODE='23514'; END IF;
 SELECT COALESCE(d.order_ref,r.order_ref) INTO actual FROM stock_reservations r LEFT JOIN demand_lines d ON d.id=r.demand_line_id WHERE r.id=NEW.reservation_id;
 SELECT order_ref INTO intended FROM shipments WHERE id=NEW.shipment_id;
 IF intended IS NOT NULL AND intended<>actual THEN RAISE EXCEPTION 'shipment must belong to one customer order' USING ERRCODE='23514'; END IF;
 IF EXISTS(SELECT 1 FROM shipment_lines z JOIN stock_reservations r ON r.id=z.reservation_id LEFT JOIN demand_lines d ON d.id=r.demand_line_id WHERE z.shipment_id=NEW.shipment_id AND COALESCE(d.order_ref,r.order_ref)<>actual) THEN RAISE EXCEPTION 'shipment must belong to one customer order' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END; $$;
CREATE TRIGGER shipment_line_guard BEFORE INSERT ON shipment_lines FOR EACH ROW EXECUTE FUNCTION guard_shipment_line();
CREATE FUNCTION guard_dispatch() RETURNS trigger LANGUAGE plpgsql SET search_path=logistics,pg_temp AS $$
BEGIN
 PERFORM 1 FROM shipments WHERE id=NEW.shipment_id FOR UPDATE;
 IF NOT EXISTS(SELECT 1 FROM shipment_lines WHERE shipment_id=NEW.shipment_id) OR EXISTS(SELECT 1 FROM shipment_lines l WHERE l.shipment_id=NEW.shipment_id AND l.quantity<>(SELECT COALESCE(-sum(m.quantity),0) FROM stock_movements m WHERE m.shipment_line_id=l.id)) THEN RAISE EXCEPTION 'dispatch must ship all lines in full' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END; $$;
CREATE TRIGGER dispatch_guard BEFORE INSERT ON shipment_dispatches FOR EACH ROW EXECUTE FUNCTION guard_dispatch();

