CREATE FUNCTION guard_purchase_child() RETURNS trigger LANGUAGE plpgsql SET search_path=logistics,pg_temp AS $$
DECLARE pid bigint; prior_pid bigint; stat text;
BEGIN
 IF TG_TABLE_NAME='purchase_order_lines' THEN
  IF TG_OP<>'DELETE' THEN pid:=NEW.purchase_order_id; END IF;
  IF TG_OP<>'INSERT' THEN prior_pid:=OLD.purchase_order_id; END IF;
 ELSE
  IF TG_OP<>'DELETE' THEN SELECT purchase_order_id INTO pid FROM purchase_order_lines WHERE id=NEW.po_line_id; END IF;
  IF TG_OP<>'INSERT' THEN SELECT purchase_order_id INTO prior_pid FROM purchase_order_lines WHERE id=OLD.po_line_id; END IF;
 END IF;
 PERFORM 1 FROM purchase_orders WHERE id IN(pid,prior_pid) ORDER BY id FOR UPDATE;
 IF EXISTS(SELECT 1 FROM purchase_orders WHERE id IN(pid,prior_pid) AND status='approved') THEN RAISE EXCEPTION 'approved purchase lines and allocations are frozen' USING ERRCODE='23514'; END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END; $$;
